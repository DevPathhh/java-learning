public class ComparisonOperators {
    public static void main(String[]  hargs) {
        int age = 18;

        System.out.println(age == 18);
        System.out.println(age != 18);
        System.out.println(age > 18);
        System.out.println(age < 18);
        System.out.println(age >= 18);
        System.out.println(age <= 18);
    }
}
